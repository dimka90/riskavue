import { test, expect } from '@playwright/test';
test('public judge door completes without authorization or private API calls', async ({ page, request }) => {
    const api = process.env.TEST_API ?? 'http://127.0.0.1:3001/api';
    const before = await (await request.get(api + '/state')).json();
    const calls: string[] = [], errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => { if (r.url().includes('/api/')) calls.push(r.url()); });
    await page.goto('/judge');
    await page.getByRole('button', { name: 'Load the $190 scenario', exact: true }).click();
    await expect(page.locator('#judge-count')).toContainText('$190.00');
    await page.getByRole('button', { name: 'Check an oversized trade', exact: true }).click();
    await expect(page.locator('#judge-display')).toContainText('NOT SENT');
    await expect(page.locator('#judge-count')).toContainText('Paper orders: 0');
    await page.getByRole('button', { name: 'Tap to discard', exact: true }).click();
    await expect(page.locator('#judge-message')).toContainText('No order was sent');
    await page.getByRole('button', { name: 'Trigger the two-loss lock', exact: true }).click();
    await expect(page.locator('#judge-display')).toContainText('SESSION LOCKED');
    await page.getByRole('button', { name: 'Tap: try another trade', exact: true }).click();
    await expect(page.locator('#judge-message')).toContainText('STILL LOCKED');
    await page.getByRole('button', { name: 'Show Telegram /status', exact: true }).click();
    await expect(page.locator('#judge-status')).toContainText('LOCKED');
    await page.getByRole('button', { name: 'Show the three-line review', exact: true }).click();
    await expect(page.locator('#judge-review')).toContainText('Next session:');
    await expect(page.locator('#proof')).toContainText('28694211519');
    expect(calls.every(url => url.includes('/api/judge/'))).toBe(true);
    const after = await (await request.get(api + '/state')).json();
    expect(after.account.orders).toEqual(before.account.orders);
    expect(after.lock).toEqual(before.lock);
    expect(errors).toEqual([]);
    await page.screenshot({ path: '.artifacts/judge/desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    await page.screenshot({ path: '.artifacts/judge/mobile.png', fullPage: true });
});
